"""A7 evaluation runner (docs/assistant/A7_PLAN.md).

    python -m app.assistant.a7.runner SUITE [SUITE ...]     (run in backend/; `make a7-eval`)

Every suite runs on the development stack: conversations in a throwaway PostgreSQL
database, evidence read-only from the development corpus, no live LLM (see `live.py` for
the opt-in live run). Each suite writes `docs/assistant/a7/<suite>.md` and a JSON record
under `data/processed/a7/`, and returns whether its hard gates passed.
"""

from __future__ import annotations

import argparse
import asyncio
import contextlib
import json
import logging
import subprocess
import sys
import time
from collections.abc import Awaitable, Callable
from datetime import UTC, datetime
from typing import Any

from app.assistant.a7.datasets import REPO_ROOT, load_conversations
from app.assistant.a7.driver import run_turns
from app.assistant.a7.probes import CapturingChecklist
from app.assistant.a7.stack import Stack, development_checklist, throwaway_database
from app.core.loop import selector_loop_factory

REPORT_DIR = REPO_ROOT / "docs" / "assistant" / "a7"
RECORD_DIR = REPO_ROOT / "data" / "processed" / "a7"

Suite = Callable[["Context"], Awaitable[dict[str, Any]]]
SUITES: dict[str, Suite] = {}


def suite(name: str) -> Callable[[Suite], Suite]:
    def register(fn: Suite) -> Suite:
        SUITES[name] = fn
        return fn

    return register


class Context:
    """Shared by the suites of one run: the stack and the run's provenance."""

    def __init__(self, stack: Stack, checklist: CapturingChecklist) -> None:
        self.stack = stack
        self.checklist = checklist
        self.provenance = provenance()


def provenance() -> dict[str, Any]:
    from app.assistant.catalogue import catalogue
    from app.assistant.coverage import coverage

    def git(*args: str) -> str:
        try:
            return subprocess.run(  # noqa: S603 - fixed git arguments
                ["git", *args],  # noqa: S607 - git on PATH, fixed arguments
                cwd=REPO_ROOT,
                capture_output=True,
                text=True,
                check=True,  # noqa: S607
            ).stdout.strip()
        except (OSError, subprocess.CalledProcessError):
            return "unknown"

    return {
        "date": datetime.now(UTC).isoformat(timespec="seconds"),
        "commit": git("rev-parse", "--short", "HEAD"),
        "dirty": bool(git("status", "--porcelain")),
        "coverage_version": coverage().version,
        "catalogue_version": catalogue().version,
        "manifest_sha256": manifest_hashes(),
    }


def manifest_hashes() -> dict[str, str]:
    import yaml

    data = yaml.safe_load((REPO_ROOT / "data" / "raw_pdfs" / "manifest.yaml").read_text("utf-8"))
    return {d["document_key"]: d["sha256"][:16] for d in data}


def write_report(name: str, markdown: str, record: dict[str, Any]) -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    RECORD_DIR.mkdir(parents=True, exist_ok=True)
    (REPORT_DIR / f"{name}.md").write_text(markdown, encoding="utf-8", newline="\n")
    (RECORD_DIR / f"{name}.json").write_text(
        json.dumps(record, indent=2, ensure_ascii=False, default=str) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def header(title: str, ctx: Context) -> str:
    p = ctx.provenance
    return (
        f"# A7: {title}\n\n"
        f"Generated by `python -m app.assistant.a7.runner` on {p['date']} at commit "
        f"`{p['commit']}`{' (with uncommitted changes)' if p['dirty'] else ''}; coverage "
        f"`{p['coverage_version']}`, catalogue `{p['catalogue_version']}`. Development "
        "stack, throwaway conversation database, no live LLM. Synthetic data only.\n\n"
    )


# --- suites --------------------------------------------------------------------------------------


@suite("smoke")
async def smoke(ctx: Context) -> dict[str, Any]:
    """One conversation end to end on the real stack (checks the harness itself)."""
    conv = next(c for c in load_conversations().conversations if c.id == "sep-01")
    started = time.perf_counter()
    run = await run_turns(ctx.stack.service(), conv.turns, restart=ctx.stack.service)
    ok = run.passed and ctx.checklist.built != []
    md = header("harness smoke test", ctx) + (
        f"- conversation `{conv.id}`: {'pass' if run.passed else 'FAIL'}\n"
        f"- checklists built from the stored corpus: {len(ctx.checklist.built)}\n"
        f"- elapsed: {time.perf_counter() - started:.1f} s\n"
    )
    write_report("smoke", md, {"provenance": ctx.provenance, "passed": ok})
    return {"passed": ok}


# --- entry point ---------------------------------------------------------------------------------


async def _run(
    names: list[str], url: str, checklist: CapturingChecklist
) -> dict[str, dict[str, Any]]:
    results: dict[str, dict[str, Any]] = {}
    stack = Stack(url, checklist)
    ctx = Context(stack, checklist)
    try:
        for name in names:
            results[name] = await SUITES[name](ctx)
            print(f"{name}: {'PASS' if results[name]['passed'] else 'FAIL'}")
    finally:
        await stack.close()
    return results


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.WARNING)
    # Import the later stages' suites so they register (kept in their own modules).
    for module in ("suites_evidence", "suites_conversation", "suites_privacy"):
        with contextlib.suppress(ModuleNotFoundError):
            __import__(f"app.assistant.a7.{module}")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("suites", nargs="+", choices=[*SUITES, "all"])
    args = parser.parse_args(argv)
    names = [n for n in SUITES if n != "smoke"] if "all" in args.suites else args.suites
    checklist = CapturingChecklist(development_checklist())  # dev settings, before the switch
    # The database is created and migrated outside the evaluation loop (alembic runs its own).
    with (
        throwaway_database() as url,
        asyncio.Runner(loop_factory=selector_loop_factory) as runner,
    ):
        results = runner.run(_run(names, url, checklist))
    return 0 if all(r["passed"] for r in results.values()) else 1


if __name__ == "__main__":
    sys.exit(main())
