"""Shared by the A7 runner and its suites: the suite registry, the run context and the
report writers (a separate module so `python -m ...runner` registers suites only once)."""

from __future__ import annotations

import json
import subprocess
from collections.abc import Awaitable, Callable
from datetime import UTC, datetime
from typing import Any

from app.assistant.a7.datasets import REPO_ROOT
from app.assistant.a7.probes import CapturingChecklist
from app.assistant.a7.stack import Stack

REPORT_DIR = REPO_ROOT / "docs" / "assistant" / "a7"
RECORD_DIR = REPO_ROOT / "data" / "processed" / "a7"

Suite = Callable[["Context"], Awaitable[dict[str, Any]]]
SUITES: dict[str, Suite] = {}


def suite(name: str) -> Callable[[Suite], Suite]:
    def register(fn: Suite) -> Suite:
        SUITES[name] = fn
        return fn

    return register


class Context:
    """Shared by the suites of one run: the stack and the run's provenance."""

    def __init__(self, stack: Stack, checklist: CapturingChecklist, dev_settings: Any) -> None:
        self.stack = stack
        self.checklist = checklist
        # The development settings, captured before DATABASE_URL points at the throwaway
        # database: the corpus (chunks, documents) is read through these, read-only.
        self.dev_settings = dev_settings
        self.provenance = provenance()


def provenance() -> dict[str, Any]:
    from app.assistant.catalogue import catalogue
    from app.assistant.coverage import coverage

    def git(*args: str) -> str:
        try:
            return subprocess.run(  # noqa: S603 - fixed git arguments
                ["git", *args],  # noqa: S607 - git on PATH, fixed arguments
                cwd=REPO_ROOT,
                capture_output=True,
                text=True,
                check=True,  # noqa: S607
            ).stdout.strip()
        except (OSError, subprocess.CalledProcessError):
            return "unknown"

    return {
        "date": datetime.now(UTC).isoformat(timespec="seconds"),
        "commit": git("rev-parse", "--short", "HEAD"),
        "dirty": bool(git("status", "--porcelain")),
        "coverage_version": coverage().version,
        "catalogue_version": catalogue().version,
        "manifest_sha256": manifest_hashes(),
    }


def manifest_hashes() -> dict[str, str]:
    import yaml

    data = yaml.safe_load((REPO_ROOT / "data" / "raw_pdfs" / "manifest.yaml").read_text("utf-8"))
    return {d["document_key"]: d["sha256"][:16] for d in data}


def write_report(name: str, markdown: str, record: dict[str, Any]) -> None:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    RECORD_DIR.mkdir(parents=True, exist_ok=True)
    (REPORT_DIR / f"{name}.md").write_text(markdown, encoding="utf-8", newline="\n")
    (RECORD_DIR / f"{name}.json").write_text(
        json.dumps(record, indent=2, ensure_ascii=False, default=str) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def header(title: str, ctx: Context) -> str:
    p = ctx.provenance
    return (
        f"# A7: {title}\n\n"
        f"Generated by `python -m app.assistant.a7.runner` on {p['date']} at commit "
        f"`{p['commit']}`{' (with uncommitted changes)' if p['dirty'] else ''}; coverage "
        f"`{p['coverage_version']}`, catalogue `{p['catalogue_version']}`. Development "
        "stack, throwaway conversation database, no live LLM. Synthetic data only.\n\n"
    )
